import {
  generateProjectPlan,
  breakdownTask,
  predictSprintRisk,
  askCopilot,
} from '../services/geminiService.js';
import { sendSuccess, sendError } from '../utils/response.js';

export const planProject = async (req, res, next) => {
  try {
    const { goal, techStack } = req.body;
    if (!goal) {
      return sendError(res, 400, 'Please provide a project goal or prompt');
    }

    const plan = await generateProjectPlan(goal, techStack);
    return sendSuccess(res, 200, 'Project plan generated by Gemini AI', { plan });
  } catch (error) {
    next(error);
  }
};

export const decomposeTask = async (req, res, next) => {
  try {
    const { title, context } = req.body;
    if (!title) {
      return sendError(res, 400, 'Please provide a task title');
    }

    const subtasks = await breakdownTask(title, context);
    return sendSuccess(res, 200, 'Task breakdown generated by Gemini AI', { subtasks });
  } catch (error) {
    next(error);
  }
};

export const analyzeRisks = async (req, res, next) => {
  try {
    const sprintData = req.body || {};
    const riskAnalysis = await predictSprintRisk(sprintData);
    return sendSuccess(res, 200, 'Sprint risk analysis generated', { riskAnalysis });
  } catch (error) {
    next(error);
  }
};

export const copilotChat = async (req, res, next) => {
  try {
    const { prompt, context } = req.body;
    if (!prompt) {
      return sendError(res, 400, 'Please provide a query prompt');
    }

    const reply = await askCopilot(prompt, context);
    return sendSuccess(res, 200, 'Copilot response received', { reply });
  } catch (error) {
    next(error);
  }
};
